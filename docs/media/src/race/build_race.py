"""Build race/race-data.js (scene 2 and the race GIF) from the captured stream timings in race/race_capture.json.

    python docs/media/src/race/build_race.py [--tokenizer path/to/tokenizer.json]

race_capture.json holds, per engine, the arrival time of every streamed chunk (seconds since the request was sent)
and its text, for one greedy run of the same token-id prompt (capture: race/capture.py). Nothing here smooths or
rescales a time: the scene plays these times at 1x. Token counts per chunk come from tokenizing the streamed text
with the model's tokenizer; the final count is the server's own completion_tokens.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent


def last_number(s):
    nums = re.findall(r"-?\d[\d,]*\.?\d*", s)
    return nums[-1].replace(",", "").rstrip(".") if nums else None


def decode_rate(chunks, n):
    """bench/serve_bench.py's decode tok/s: (tokens - 1) / (last chunk - first chunk)."""
    d = chunks[-1][0] - chunks[0][0]
    return (n - 1) / d if d > 0 else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--capture", default=str(HERE / "race_capture.json"))
    ap.add_argument("--tokenizer", default=None, help="tokenizer.json of Inkling-2-Mini (for per-chunk token counts)")
    ap.add_argument("--out", default=str(HERE / "race-data.js"))
    a = ap.parse_args()
    cap = json.load(open(a.capture))
    tok = None
    if a.tokenizer:
        import tokenizers
        tok = tokenizers.Tokenizer.from_file(a.tokenizer)

    engines, ends = [], {}
    for e in cap["engines"]:
        chunks = e["chunks"]
        text = "".join(c[1] for c in chunks)
        n = e["completion_tokens"]
        events, chars = [], 0
        for t, s in chunks:
            chars += len(s)
            k = len(tok.encode(text[:chars], add_special_tokens=False).ids) if tok else round(n * chars / len(text))
            events.append([round(t, 4), min(k, n), chars])
        events[-1][1] = n
        for i in range(1, len(events)):  # monotone after the tokenizer's boundary effects
            events[i][1] = max(events[i][1], events[i - 1][1])
        answer = text[e["answer_start"]:]
        correct = last_number(answer) == cap["label"]
        assert correct, f"{e['name']}: answer {last_number(answer)!r} vs key {cap['label']!r}"
        ends[e["key"]] = events[-1][0]
        engines.append({"key": e["key"], "name": e["name"], "label": e["label"], "ours": e["key"].startswith("ours"),
                        "events": events, "text": text, "answer_start": e["answer_start"], "tokens": n,
                        "t_end": events[-1][0], "tok_s": round(decode_rate(chunks, n), 1), "correct": correct})

    ours = next(x for x in engines if x["ours"])
    fastest = min((x for x in engines if not x["ours"]), key=lambda x: x["t_end"])
    ratio = fastest["t_end"] / ours["t_end"]
    # the same 6 decode-benchmark prompts, re-measured in this capture (mean of the two repeats)
    b6 = {k: sum(v["overall_tok_s_reps"]) / len(v["overall_tok_s_reps"]) for k, v in cap["bench6"].items()}
    ours_k = next(k for k in b6 if k.startswith("ours"))
    b6_base = max((k for k in b6 if k != ours_k), key=lambda k: b6[k])
    b6_ratio = b6[ours_k] / b6[b6_base]
    b6_name = next(e["name"] for e in cap["engines"] if e["key"] == b6_base).split(" ")[0]
    data = {
        "layout": cap["layout"],
        "headline": cap["headline"],
        "question": cap["question"],
        "punchline": f"Same answer, {ratio:.1f}× sooner than {fastest['name']}.",
        "punchsub": f"This question. 6-prompt average in this run: {b6_ratio:.2f}× vs the faster baseline ({b6_name}).",
        "footer": [f"Answer key: {cap['label']} · request sent to last token · greedy · DSpark on all three",
                   "RTX PRO 6000 (the RTX 5090's GB202 chip), 32 GB budget per engine"],
        "engines": engines,
        "ratio": round(ratio, 3),
        "bench6_ratio": round(b6_ratio, 3),
    }
    pathlib.Path(a.out).write_text("// generated by build_race.py from race_capture.json; do not edit\nwindow.RACE = "
                                   + json.dumps(data, ensure_ascii=False) + ";\n")
    for x in engines:
        print(f"{x['name']:12s} end {x['t_end']:.3f} s  tokens {x['tokens']}  decode {x['tok_s']} tok/s  correct {x['correct']}")
    print(f"ratio vs {fastest['name']} (end to end) = {ratio:.3f}; 6-prompt ratio this run = {b6_ratio:.3f}")


if __name__ == "__main__":
    main()
